-- Who Sabi? — analytics store (ClickHouse 24.8 LTS or newer)
-- Feeds the admin console (doc 18) and the metrics in doc 13.
--
-- Two kinds of events land here:
--   * client events from the app (Android, iOS, web) and the party web client: sessions, screens, taps, time
--   * server events from the API, realtime and workers: answers, matches, coins, purchases, pushes (the source of truth)
--
-- Privacy rules for this database (doc 10 §3):
--   * No direct identifiers. A user is `user_pid` = HMAC-SHA256(user_id, analytics key). The key lives in
--     AWS Secrets Manager and only the admin API can map a pid back to a user; every lookup is audited.
--   * Never written here: phone numbers, emails, usernames, nicknames, free text, contacts, precise location, IP addresses.
--   * `geo_state` is an approximate state worked out from the IP at ingest. The IP itself is dropped.
--   * Raw events are kept 13 months, per-user rollups 25 months. Account deletion removes the user's rows.
--
-- Each event is counted once:
--   * The ingest service accepts each client batch once: its batch_id is checked and the batch appended to the
--     Redis stream in one atomic Redis script, so a resent batch is acknowledged and dropped.
--   * The loader inserts each stream chunk with SETTINGS insert_deduplication_token = '<first id>-<last id>',
--     deduplicate_blocks_in_dependent_materialized_views = 1. A retried insert is ignored, rollups included.
--     (ClickHouse Cloud and replicated tables keep a deduplication window by default; single servers use the
--     non_replicated_deduplication_window setting below.)
--   * ReplacingMergeTree on `events` removes any duplicate that still slips through (same event_id).

CREATE DATABASE IF NOT EXISTS analytics;

-- ===================== RAW EVENTS =====================
CREATE TABLE analytics.events
(
    event_id      UUID,                                   -- generated by the sender; retries reuse it
    event         LowCardinality(String),                 -- e.g. 'screen_viewed', 'duel_completed' (tracking plan, doc 13)
    source        Enum8('client' = 1, 'server' = 2),
    ts            DateTime64(3, 'UTC'),                   -- event time, corrected for device clock skew at ingest
    received_at   DateTime64(3, 'UTC') DEFAULT now64(3),
    wat_date      Date MATERIALIZED toDate(ts, 'Africa/Lagos'),
    user_pid      String,                                 -- pseudonymous user id (guests have one too)
    anon_id       String,                                 -- install id (app) or browser id (web)
    session_id    String,                                 -- '' for server events not tied to a session (webhooks, jobs)
    seq           UInt32,                                 -- order within the session
    platform      LowCardinality(String),                 -- 'android' | 'ios' | 'web'
    app_version   LowCardinality(String),
    os_version    LowCardinality(String),
    device_model  LowCardinality(String),
    browser       LowCardinality(String),                 -- web only, e.g. 'chrome_android', 'safari_ios', 'whatsapp_inapp'
    ram_mb        UInt16,
    network_type  LowCardinality(String),                 -- 'wifi' | '4g' | '3g' | '2g' | 'offline'
    carrier       LowCardinality(String),                 -- 'MTN' | 'Airtel' | 'Glo' | 'T2' | ''
    geo_state     LowCardinality(String),                 -- approximate, from IP at ingest
    home_state    LowCardinality(String),                 -- the user's chosen state, if any
    language      LowCardinality(String),
    age_band      LowCardinality(String),
    data_saver    Bool,
    screen        LowCardinality(String),                 -- screen the user was on when the event happened
    props         String CODEC(ZSTD(3)),                  -- JSON object with the event's own properties
    INDEX idx_user    user_pid   TYPE bloom_filter(0.01) GRANULARITY 4,
    INDEX idx_session session_id TYPE bloom_filter(0.01) GRANULARITY 4
)
ENGINE = ReplacingMergeTree(received_at)                  -- retried duplicates (same event_id) are merged away
PARTITION BY toYYYYMM(wat_date)
ORDER BY (event, wat_date, user_pid, event_id)
TTL wat_date + INTERVAL 13 MONTH DELETE
SETTINGS ttl_only_drop_parts = 1, non_replicated_deduplication_window = 1000;

-- Events that failed validation against the tracking plan. Short retention, analysts and engineers only.
CREATE TABLE analytics.events_quarantine
(
    received_at   DateTime64(3, 'UTC') DEFAULT now64(3),
    reason        LowCardinality(String),                 -- 'unknown_event' | 'bad_props' | 'pii_suspected' | 'too_old'
    payload       String CODEC(ZSTD(3))
)
ENGINE = MergeTree
ORDER BY received_at
TTL toDateTime(received_at) + INTERVAL 30 DAY DELETE;

-- ===================== SESSIONS & TIME SPENT =====================
-- One row per session per WAT day; a session that crosses midnight counts towards both days.
-- Time spent = foreground time, reported by the client in `app_backgrounded.foreground_ms` (time visible since the
-- last foreground). If the last report is lost (crash, app killed), the admin falls back to the session's span.
CREATE TABLE analytics.session_days
(
    wat_date        Date,
    user_pid        String,
    session_id      String,
    platform        LowCardinality(String),
    first_event_at  SimpleAggregateFunction(min, DateTime64(3, 'UTC')),
    last_event_at   SimpleAggregateFunction(max, DateTime64(3, 'UTC')),
    foreground_ms   SimpleAggregateFunction(sum, UInt64),
    events          SimpleAggregateFunction(sum, UInt64),
    screens         SimpleAggregateFunction(sum, UInt64)
)
ENGINE = AggregatingMergeTree
PARTITION BY toYYYYMM(wat_date)
ORDER BY (wat_date, user_pid, session_id, platform)
TTL wat_date + INTERVAL 25 MONTH DELETE
SETTINGS non_replicated_deduplication_window = 1000;

CREATE MATERIALIZED VIEW analytics.session_days_mv TO analytics.session_days AS
SELECT
    wat_date,
    user_pid,
    session_id,
    platform,
    min(ts)                                                                     AS first_event_at,
    max(ts)                                                                     AS last_event_at,
    sumIf(JSONExtractUInt(props, 'foreground_ms'), event = 'app_backgrounded')  AS foreground_ms,
    count()                                                                     AS events,
    countIf(event = 'screen_viewed')                                            AS screens
FROM analytics.events
WHERE source = 'client' AND session_id != ''
GROUP BY wat_date, user_pid, session_id, platform;

-- ===================== TIME ON EACH SCREEN =====================
-- Screens are named '<area>.<screen>' (e.g. 'duel.question', 'shop.home'), so time by mode = time by area.
-- Each view is closed exactly once: by the next `screen_viewed` (prev_screen, prev_screen_ms) or by
-- `app_backgrounded` (screen, screen_ms). On return to the foreground the client re-sends `screen_viewed`
-- with an empty prev_screen.
CREATE TABLE analytics.screen_days
(
    wat_date    Date,
    user_pid    String,
    platform    LowCardinality(String),
    screen      LowCardinality(String),
    ms          SimpleAggregateFunction(sum, UInt64),
    views       SimpleAggregateFunction(sum, UInt64)
)
ENGINE = AggregatingMergeTree
PARTITION BY toYYYYMM(wat_date)
ORDER BY (wat_date, screen, user_pid, platform)
TTL wat_date + INTERVAL 25 MONTH DELETE
SETTINGS non_replicated_deduplication_window = 1000;

CREATE MATERIALIZED VIEW analytics.screen_days_views_mv TO analytics.screen_days AS
SELECT
    wat_date,
    user_pid,
    platform,
    JSONExtractString(props, 'prev_screen')        AS screen,
    sum(JSONExtractUInt(props, 'prev_screen_ms'))  AS ms,
    count()                                        AS views
FROM analytics.events
WHERE event = 'screen_viewed' AND JSONExtractString(props, 'prev_screen') != ''
GROUP BY wat_date, user_pid, platform, screen;

CREATE MATERIALIZED VIEW analytics.screen_days_background_mv TO analytics.screen_days AS
SELECT
    wat_date,
    user_pid,
    platform,
    JSONExtractString(props, 'screen')             AS screen,
    sum(JSONExtractUInt(props, 'screen_ms'))       AS ms,
    count()                                        AS views
FROM analytics.events
WHERE event = 'app_backgrounded' AND JSONExtractString(props, 'screen') != ''
GROUP BY wat_date, user_pid, platform, screen;

-- ===================== PER-USER DAILY ROLLUP =====================
-- Drives DAU/WAU/MAU, retention cohorts, time spent, and the charts on the User 360 page.
CREATE TABLE analytics.user_days
(
    wat_date              Date,
    user_pid              String,
    platform              LowCardinality(String),
    events                SimpleAggregateFunction(sum, UInt64),
    foreground_ms         SimpleAggregateFunction(sum, UInt64),
    questions_answered    SimpleAggregateFunction(sum, UInt64),
    questions_correct     SimpleAggregateFunction(sum, UInt64),
    matches_completed     SimpleAggregateFunction(sum, UInt64),
    coins_earned          SimpleAggregateFunction(sum, Int64),
    coins_spent           SimpleAggregateFunction(sum, Int64),
    ads_rewarded          SimpleAggregateFunction(sum, UInt64),
    ad_revenue_usd_micros SimpleAggregateFunction(sum, UInt64),  -- estimate, from AdMob impression-level revenue
    purchase_net_kobo     SimpleAggregateFunction(sum, Int64)    -- after store / Paystack fees; refunds are negative
)
ENGINE = AggregatingMergeTree
PARTITION BY toYYYYMM(wat_date)
ORDER BY (wat_date, user_pid, platform)
TTL wat_date + INTERVAL 25 MONTH DELETE
SETTINGS non_replicated_deduplication_window = 1000;

CREATE MATERIALIZED VIEW analytics.user_days_mv TO analytics.user_days AS
SELECT
    wat_date,
    user_pid,
    platform,
    count()                                                                                    AS events,
    sumIf(JSONExtractUInt(props, 'foreground_ms'), event = 'app_backgrounded')                 AS foreground_ms,
    countIf(event = 'question_answered')                                                       AS questions_answered,
    countIf(event = 'question_answered' AND JSONExtractBool(props, 'correct'))                 AS questions_correct,
    countIf(event IN ('duel_completed', 'party_game_completed', 'daily_completed'))            AS matches_completed,
    sumIf(JSONExtractInt(props, 'delta'), event = 'coins_changed' AND JSONExtractInt(props, 'delta') > 0)  AS coins_earned,
    sumIf(-JSONExtractInt(props, 'delta'), event = 'coins_changed' AND JSONExtractInt(props, 'delta') < 0) AS coins_spent,
    countIf(event = 'ad_reward_granted')                                                       AS ads_rewarded,
    sumIf(JSONExtractUInt(props, 'value_micros'), event = 'ad_paid')                           AS ad_revenue_usd_micros,
    sumIf(JSONExtractInt(props, 'net_kobo'), event IN ('purchase_completed', 'purchase_refunded')) AS purchase_net_kobo
FROM analytics.events
WHERE user_pid != ''
GROUP BY wat_date, user_pid, platform;

-- ===================== DIMENSIONS (synced from the Postgres read replica every 5 minutes) =====================
-- No PII: only attributes needed to slice metrics.
CREATE TABLE analytics.users_dim
(
    user_pid            String,
    status              LowCardinality(String),           -- 'guest' | 'active' | 'restricted' | 'banned' | 'deleted'
    signup_platform     LowCardinality(String),
    acquisition_source  LowCardinality(String),           -- 'organic' | 'invite' | 'creator:<code>' | 'ambassador:<code>' | 'ads:<network>'
    age_band            LowCardinality(String),
    home_state          LowCardinality(String),
    created_at          DateTime64(3, 'UTC'),
    updated_at          DateTime64(3, 'UTC')
)
ENGINE = ReplacingMergeTree(updated_at)
ORDER BY user_pid;

-- When a guest signs in to an existing account (FR-AUTH-4), the guest's events stay under the guest pid.
-- This table links them so timelines and cohorts follow the person, not the device.
CREATE TABLE analytics.user_aliases
(
    alias_pid       String,
    canonical_pid   String,
    merged_at       DateTime64(3, 'UTC')
)
ENGINE = ReplacingMergeTree(merged_at)
ORDER BY alias_pid;

CREATE TABLE analytics.questions_dim
(
    question_id     String,
    category_id     LowCardinality(String),
    subcategory     LowCardinality(String),
    difficulty      UInt8,
    d_rating        Float32,
    status          LowCardinality(String),
    updated_at      DateTime64(3, 'UTC')
)
ENGINE = ReplacingMergeTree(updated_at)
ORDER BY question_id;

-- ===================== PEOPLE, NOT IDS =====================
-- Metrics count people: a guest id that was merged into an account counts as that account.
-- A new merge reaches the metrics within 5 minutes (dictionary refresh).
-- In production, add USER/PASSWORD to the CLICKHOUSE source for a read-only user.
CREATE DICTIONARY analytics.user_alias_dict
(
    alias_pid       String,
    canonical_pid   String
)
PRIMARY KEY alias_pid
SOURCE(CLICKHOUSE(QUERY 'SELECT alias_pid, canonical_pid FROM analytics.user_aliases FINAL'))
LIFETIME(MIN 60 MAX 300)
LAYOUT(COMPLEX_KEY_HASHED());

-- The per-person daily table every KPI is built on (DAU, time spent, retention, revenue per user).
CREATE VIEW analytics.person_days AS
SELECT
    wat_date,
    dictGetOrDefault('analytics.user_alias_dict', 'canonical_pid', tuple(user_pid), user_pid) AS person_pid,
    platform,
    sum(events)                AS events,
    sum(foreground_ms)         AS foreground_ms,
    sum(questions_answered)    AS questions_answered,
    sum(questions_correct)     AS questions_correct,
    sum(matches_completed)     AS matches_completed,
    sum(coins_earned)          AS coins_earned,
    sum(coins_spent)           AS coins_spent,
    sum(ads_rewarded)          AS ads_rewarded,
    sum(ad_revenue_usd_micros) AS ad_revenue_usd_micros,
    sum(purchase_net_kobo)     AS purchase_net_kobo
FROM analytics.user_days
GROUP BY wat_date, person_pid, platform;

